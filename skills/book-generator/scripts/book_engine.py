from pathlib import Path

EBOOK_FORMATS = ("epub", "pdf", "html", "markdown", "mobi", "azw3")
AUDIO_FORMATS = ("mp3", "m4b")
GROUPS = {
    "ebook": EBOOK_FORMATS,
    "audiobook": AUDIO_FORMATS,
    "all": EBOOK_FORMATS + AUDIO_FORMATS,
}

# Language -> labels and default TTS voice (Microsoft neural voices via edge-tts).
LANGUAGES = {
    "pt-BR": {"toc": "Sumário", "voice": "pt-BR-FranciscaNeural", "default_title": "Livro"},
    "pt": {"toc": "Sumário", "voice": "pt-BR-FranciscaNeural", "default_title": "Livro"},
    "en": {"toc": "Table of Contents", "voice": "en-US-AriaNeural", "default_title": "Book"},
    "en-US": {"toc": "Table of Contents", "voice": "en-US-AriaNeural", "default_title": "Book"},
}

# Lines that AI authoring tools leave behind. Same patterns as compile_book.sh,
# used only in non-strict mode. (The awk pass of compile_book.sh is NOT copied:
# it drops everything after the first matching line.)
ARTIFACT_PATTERNS = [
    r"^(PLAGIARISM|COPYRIGHT)[ _/]*ANALYSIS:?",
    r"^(COPYRIGHT|PLAGIARISM)[ _/]*RISK:?",
    r"^FLAGGED[ _]*SECTIONS:?",
    r"^(ISSUES|PROBLEMS)[ _]*FOUND:?",
    r"^WRITING[ _]*GUIDELINES:?",
    r"^DETAILED[ _]*ANALYSIS:?",
    r"^RECOMMENDATIONS?:?",
    r"^IMPORTANT[ _]*WORD[ _]*COUNT[ _]*REQUIREMENT:?",
    r"^REWRITING[ _]*REQUIREMENTS?:?",
    r"^The final answer is:",
    r"^\**The content needs to be rewritten",
    r"^\*\*WRITING[ _]*GUIDELINES:?\*\*",
    r"^\*\*PLAGIARISM[ _/]*ANALYSIS:?\*\*",
    r"^\*\*COPYRIGHT[ _]*ANALYSIS:?\*\*",
    r"^\*\*REWRITING[ _]*REQUIREMENTS:?\*\*",
    r"^ORIGINALITY[ _]*SCORE:?",
    r"^PLAGIARISM[ _]*RISK:?",
    r"^COPYRIGHT[ _]*RISK:?",
    r"^ISSUES[ _]*FOUND:?",
    r"^Chapter Rewrite:?",
    r"^Please rewrite the entire chapter",
    r"^NOTE TO WRITER:?",
    r"^STYLE NOTES?:?",
    r"^AI[ _]*GENERATED[ _]*CONTENT:?",
    r"^\*\*AI[ _]*GENERATED[ _]*CONTENT:?\*\*",
    r"^Generated with AI",
    r"^This content was generated by",
    # Prompt leftovers that the repo's awk pass tried to catch. Only the line itself is removed.
    r"^\**(Word count|Chapter length):",
    r"^\**(Next steps|Next chapter|Note to editor):",
    r"^\**Note: this chapter",
    r"^\**As requested, this chapter",
    r"^\**End of chapter",
    r"^\**I have (written|created|completed) ",
    r"^\**This draft (meets|satisfies|fulfills)",
    r"^\**This chapter (meets|follows|adheres to)",
]
ARTIFACT_RES = [re.compile(p, re.IGNORECASE) for p in ARTIFACT_PATTERNS]

# Raw blocks that pandoc passes through only to one output family.
PAGEBREAK_BLOCK = (
    "\n```{=latex}\n\\newpage\n```\n"
    "\n```{=html}\n<div style=\"page-break-before: always;\"></div>\n```\n\n"
)

PDF_ENGINES = ("lualatex", "xelatex", "pdflatex")
CALIBRE_FALLBACKS = [
    r"C:\Program Files\Calibre2\ebook-convert.exe",
    r"C:\Program Files\Calibre\ebook-convert.exe",
]


# --------------------------------------------------------------------------- #
# Data
# --------------------------------------------------------------------------- #
@dataclass
class Block:
    path: Path
    sha256: str
    text: str          # normalized (LF) source text, exactly as written
    expected: str      # text that must appear verbatim in the manuscript
    title: str         # chapter title used for TOC/audio chapter markers


@dataclass
class Meta:
    title: str
    subtitle: str
    author: str
    language: str
    publisher: str
    year: str
    isbn: str


@dataclass
class Context:
    blocks: list[Block]
    meta: Meta
    strict: bool
    out_dir: Path
    cover: Path | None
    manifest: dict = field(default_factory=dict)


# --------------------------------------------------------------------------- #
# Source handling
# --------------------------------------------------------------------------- #
def natural_key(p: Path):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", p.name)]


def collect_sources(source: Path) -> list[Path]:
    if source.is_file():
        if source.suffix.lower() != ".md":
            raise ValueError(f"o arquivo de origem precisa ser .md: {source}")
        return [source]
    if source.is_dir():
        files = [
            p for p in source.iterdir()
            if p.is_file() and p.suffix.lower() == ".md" and not p.name.startswith(("_", "."))
        ]
        if not files:
            raise ValueError(f"nenhum .md encontrado em {source}")
        return sorted(files, key=natural_key)
    raise ValueError(f"origem não encontrada: {source}")


def first_heading(text: str) -> str | None:
    for line in text.split("\n"):
        m = re.match(r"^#{1,6}\s+(.+?)\s*(\{[^}]*\})?\s*$", line)
        if m:
            return m.group(1).strip()
    return None


def clean_artifacts(text: str, removed: list[dict], origin: str) -> str:
    kept = []
    for number, line in enumerate(text.split("\n"), start=1):
        if any(rx.search(line) for rx in ARTIFACT_RES):
            removed.append({"file": origin, "line": number, "text": line})
            continue
        kept.append(line)
    return "\n".join(kept)


def load_blocks(paths: list[Path], strict: bool) -> tuple[list[Block], list[dict]]:
    blocks, removed = [], []
    for p in paths:
        raw = p.read_bytes()
        text = raw.decode("utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
        expected = text if strict else clean_artifacts(text, removed, p.name)
        title = first_heading(text) or p.stem
        blocks.append(Block(
            path=p,
            sha256=hashlib.sha256(raw).hexdigest(),
            text=text,
            expected=expected,
            title=title,
        ))
    return blocks, removed


# --------------------------------------------------------------------------- #
# Manuscript assembly and verification
# --------------------------------------------------------------------------- #
def yaml_str(value: str) -> str:
    # JSON strings are valid YAML scalars and keep accents readable.
    return json.dumps(value, ensure_ascii=False)


def build_manuscript(blocks: list[Block], meta: Meta) -> str:
    labels = LANGUAGES.get(meta.language, LANGUAGES["pt-BR"])
    front = ["---", f"title: {yaml_str(meta.title)}"]
    if meta.subtitle:
        front.append(f"subtitle: {yaml_str(meta.subtitle)}")
    if meta.author:
        front.append(f"author: {yaml_str(meta.author)}")
    front.append(f"lang: {yaml_str(meta.language)}")
    front.append(f"toc-title: {yaml_str(labels['toc'])}")
    if meta.publisher:
        front.append(f"publisher: {yaml_str(meta.publisher)}")
    if meta.author:
        front.append(f"rights: {yaml_str(f'Copyright © {meta.year} {meta.author}')}")
    if meta.isbn:
        front.append(f"identifier: {yaml_str(meta.isbn)}")
    front.append("---")
    parts = ["\n".join(front) + "\n"]
    for index, block in enumerate(blocks):
        if index > 0:
            parts.append(PAGEBREAK_BLOCK)
        parts.append(block.expected.rstrip("\n") + "\n")
    return "".join(parts)


def verify_verbatim(manuscript: str, blocks: list[Block]) -> list[str]:
    """Return the names of source files whose text is not in the manuscript."""
    missing = []
    for block in blocks:
        needle = block.expected.rstrip("\n")
        if needle and needle not in manuscript:
            missing.append(block.path.name)
    return missing


# --------------------------------------------------------------------------- #
# Tool discovery
# --------------------------------------------------------------------------- #
def find_tool(name: str, fallbacks: list[str] | None = None) -> str | None:
    found = shutil.which(name)
    if found:
        return found
    for candidate in fallbacks or []:
        if Path(candidate).exists():
            return candidate
    return None


def tool_version(cmd: list[str]) -> str | None:
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=30, encoding="utf-8", errors="replace")
        text = (out.stdout or out.stderr or "").strip().splitlines()
        return text[0] if text else None
    except (OSError, subprocess.SubprocessError):
        return None


def edge_tts_available() -> bool:
    try:
        import edge_tts  # noqa: F401
        return True
    except ImportError:
        return False


# --------------------------------------------------------------------------- #
# Ebook formats (pandoc, LaTeX, Calibre)
# --------------------------------------------------------------------------- #
def run_checked(cmd: list[str], cwd: Path) -> None:
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if proc.returncode != 0:
        tail = "\n".join((proc.stderr or proc.stdout).strip().splitlines()[-12:])
        raise RuntimeError(f"{' '.join(cmd[:3])} saiu com código {proc.returncode}:\n{tail}")


def write_css(out_dir: Path) -> str:
    css = (
        "body { font-family: serif; line-height: 1.5; }\n"
        "h1, h2, h3 { font-family: sans-serif; page-break-after: avoid; }\n"
        "p { text-indent: 1.2em; margin: 0 0 0.3em 0; }\n"
        "h1 + p, h2 + p, h3 + p { text-indent: 0; }\n"
    )
    (out_dir / "book.css").write_text(css, encoding="utf-8")
    return "book.css"


def build_ebook(fmt: str, ctx: Context, pandoc: str | None) -> str:
    out = ctx.out_dir
    if fmt == "markdown":
        return "manuscript.md"

    if fmt in ("epub", "pdf", "html") and not pandoc:
        raise RuntimeError("pandoc não encontrado (instale com: winget install JohnMacFarlane.Pandoc)")

    if fmt == "epub":
        cmd = [pandoc, "-f", "markdown", "-t", "epub3", "--toc", "--toc-depth=2",
               "--split-level=1", "--resource-path=.", f"--css={write_css(out)}"]
        if ctx.cover:
            cmd.append(f"--epub-cover-image={ctx.cover.name}")
        cmd += ["-o", "book.epub", "manuscript.md"]
        run_checked(cmd, out)
        return "book.epub"

    if fmt == "html":
        cmd = [pandoc, "-f", "markdown", "-t", "html5", "--standalone", "--embed-resources",
               "--toc", "--toc-depth=2", f"--css={write_css(out)}", "-o", "book.html", "manuscript.md"]
        run_checked(cmd, out)
        return "book.html"

    if fmt == "pdf":
        engine = find_tool_name(PDF_ENGINES)
        if not engine:
            raise RuntimeError("nenhum motor LaTeX encontrado (lualatex, xelatex ou pdflatex); "
                               "instale MiKTeX ou TeX Live")
        cmd = [pandoc, "-f", "markdown", "-t", "pdf", f"--pdf-engine={engine}",
               "--toc", "--toc-depth=2", "--top-level-division=chapter",
               "-V", "documentclass=book", "-V", "papersize=6in,9in",
               "-V", "geometry=top=2cm", "-V", "geometry=bottom=2cm",
               "-V", "geometry=inner=2cm", "-V", "geometry=outer=2cm",
               "-o", "book.pdf", "manuscript.md"]
        run_checked(cmd, out)
        return "book.pdf"

    if fmt in ("mobi", "azw3"):
        if not (out / "book.epub").exists():
            raise RuntimeError("mobi/azw3 dependem do epub; inclua epub nos formatos ou verifique o erro do epub")
        converter = find_tool("ebook-convert", CALIBRE_FALLBACKS)
        if not converter:
            raise RuntimeError("ebook-convert (Calibre) não encontrado; instale o Calibre")
        target = f"book.{fmt}"
        cmd = [converter, "book.epub", target,
               "--title", ctx.meta.title, "--language", ctx.meta.language]
        if ctx.meta.author:
            cmd += ["--authors", ctx.meta.author]
        if ctx.meta.publisher:
            cmd += ["--publisher", ctx.meta.publisher]
        if ctx.cover:
            cmd += ["--cover", ctx.cover.name]
        run_checked(cmd, out)
        return target

    raise RuntimeError(f"formato desconhecido: {fmt}")


def find_tool_name(names: tuple[str, ...]) -> str | None:
    for name in names:
        if shutil.which(name):
            return name
    return None


# --------------------------------------------------------------------------- #
# Audiobook (edge-tts for speech, ffmpeg for joining and m4b)
# --------------------------------------------------------------------------- #
def speech_paragraphs(md: str) -> list[str]:
    """Remove Markdown syntax, keep every word. Returns speakable paragraphs."""
    s = md
    s = re.sub(r"```\{=(?:latex|tex|html)\}.*?```", "", s, flags=re.S)
    s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", "", s)
    s = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"\{[.#][^}]*\}", "", s)
    s = re.sub(r"^\s{0,3}#{1,6}\s+(.*)$",
               lambda m: m.group(1).rstrip(".") + ".", s, flags=re.M)
    s = re.sub(r"^\s*>\s?", "", s, flags=re.M)
    s = re.sub(r"^\s*([-*+]|\d+\.)\s+", "", s, flags=re.M)
    s = re.sub(r"^\s*([-*_]\s*){3,}$", "", s, flags=re.M)
    s = re.sub(r"`([^`]*)`", r"\1", s)
    s = re.sub(r"(\*\*|__)(?=\S)(.+?)(?<=\S)\1", r"\2", s)
    s = re.sub(r"(?<![\w*])\*(?=\S)(.+?)(?<=\S)\*(?![\w*])", r"\1", s)
    s = re.sub(r"(?<!\w)_(?=\S)(.+?)(?<=\S)_(?!\w)", r"\1", s)
    paragraphs = [re.sub(r"\s+", " ", p).strip() for p in re.split(r"\n\s*\n", s)]
    return [p for p in paragraphs if p]


def split_long(paragraph: str, limit: int) -> list[str]:
    if len(paragraph) <= limit:
        return [paragraph]
    sentences = re.split(r"(?<=[.!?…])\s+", paragraph)
    pieces, current = [], ""
    for sentence in sentences:
        while len(sentence) > limit:  # a single "sentence" longer than the limit
            cut = sentence.rfind(" ", 0, limit)
            cut = cut if cut > 0 else limit
            if current:
                pieces.append(current)
                current = ""
            pieces.append(sentence[:cut])
            sentence = sentence[cut:].lstrip()
        if current and len(current) + 1 + len(sentence) > limit:
            pieces.append(current)
            current = sentence
        else:
            current = f"{current} {sentence}".strip()
    if current:
        pieces.append(current)
    return pieces


def tts_chunks(paragraphs: list[str], limit: int = 2500) -> list[str]:
    chunks, current = [], ""
    for paragraph in paragraphs:
        for piece in split_long(paragraph, limit):
            if current and len(current) + 2 + len(piece) > limit:
                chunks.append(current)
                current = piece
            else:
                current = f"{current}\n\n{piece}".strip()
    if current:
        chunks.append(current)
    return chunks


async def synthesize(text: str, voice: str, rate: str, target: Path, semaphore: asyncio.Semaphore) -> None:
    import edge_tts  # imported here so the rest of the engine works without it

    async with semaphore:
        last_error = None
        for attempt in range(3):
            try:
                await edge_tts.Communicate(text, voice, rate=rate).save(str(target))
                return
            except Exception as error:  # network hiccups are retried
                last_error = error
                await asyncio.sleep(2 * (attempt + 1))
        raise RuntimeError(f"edge-tts falhou após 3 tentativas: {last_error}")


def probe_duration_ms(ffprobe: str, path: Path) -> int:
    proc = subprocess.run(
        [ffprobe, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True,
    )
    return int(float(proc.stdout.strip() or 0) * 1000)


def ffmeta_escape(value: str) -> str:
    # FFMETADATA1 treats = ; # \ and newlines as syntax; escape them.
    for char in ("\\", "=", ";", "#"):
        value = value.replace(char, "\\" + char)
    return value.replace("\n", " ")


def write_chapter_metadata(path: Path, meta: Meta, chapters: list[tuple[str, int]]) -> None:
    lines = [";FFMETADATA1", f"title={ffmeta_escape(meta.title)}"]
    if meta.author:
        lines.append(f"artist={ffmeta_escape(meta.author)}")
    start = 0
    for title, duration in chapters:
        end = start + duration
        lines += ["[CHAPTER]", "TIMEBASE=1/1000", f"START={start}", f"END={end}",
                  f"title={ffmeta_escape(title)}"]
        start = end
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_audio(ctx: Context, want_m4b: bool) -> dict[str, str]:
    """Creates audiobook/ with chapter mp3 files and book.mp3 (and book.m4b on request)."""
    if not edge_tts_available():
        raise RuntimeError("edge-tts não instalado (instale com: python -m pip install edge-tts)")
    ffmpeg = find_tool("ffmpeg")
    if want_m4b and not ffmpeg:
        raise RuntimeError("ffmpeg não encontrado (instale com: winget install Gyan.FFmpeg)")

    voice = ctx.manifest["voice"]
    rate = ctx.manifest["rate"]
    audio_dir = ctx.out_dir / "audiobook"
    parts_dir = audio_dir / "_parts"
    parts_dir.mkdir(parents=True, exist_ok=True)

    async def run_all():
        semaphore = asyncio.Semaphore(4)
        chapter_files: list[tuple[str, Path]] = []
        for number, block in enumerate(ctx.blocks, start=1):
            paragraphs = speech_paragraphs(block.expected)
            chunks = tts_chunks(paragraphs)
            if not chunks:
                continue
            tasks, chunk_paths = [], []
            for index, chunk in enumerate(chunks, start=1):
                target = parts_dir / f"{number:03d}_{index:04d}.mp3"
                chunk_paths.append(target)
                tasks.append(synthesize(chunk, voice, rate, target, semaphore))
            print(f"   🎙️  capítulo {number:02d} ({block.title}): {len(chunks)} trecho(s)")
            await asyncio.gather(*tasks)
            chapter_mp3 = audio_dir / f"{number:02d}-{slugify(block.title)}.mp3"
            with chapter_mp3.open("wb") as joined:
                for part in chunk_paths:
                    joined.write(part.read_bytes())
            chapter_files.append((block.title, chapter_mp3))
        return chapter_files

    chapter_files = asyncio.run(run_all())
    if not chapter_files:
        raise RuntimeError("nenhum texto falável nas fontes")

    book_mp3 = audio_dir / "book.mp3"
    with book_mp3.open("wb") as joined:
        for _, path in chapter_files:
            joined.write(path.read_bytes())
    shutil.rmtree(parts_dir, ignore_errors=True)
    result = {"mp3": "audiobook/book.mp3"}

    if want_m4b:
        ffprobe = find_tool("ffprobe")
        if not ffprobe:
            raise RuntimeError("ffprobe não encontrado (vem junto com o ffmpeg)")
        durations = [(title, probe_duration_ms(ffprobe, path)) for title, path in chapter_files]
        meta_file = audio_dir / "_chapters.txt"
        write_chapter_metadata(meta_file, ctx.meta, durations)
        m4b = audio_dir / "book.m4b"
        run_checked([ffmpeg, "-y", "-loglevel", "error", "-i", str(book_mp3), "-i", str(meta_file),
                     "-map_metadata", "1", "-map_chapters", "1", "-map", "0:a",
                     "-c:a", "aac", "-b:a", "64k", "-movflags", "+faststart", str(m4b)], audio_dir)
        meta_file.unlink(missing_ok=True)
        result["m4b"] = "audiobook/book.m4b"
    return result


def slugify(text: str) -> str:
    normalized = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", normalized).strip("-").lower()
    return slug[:60] or "capitulo"


