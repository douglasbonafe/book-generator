def resolve_formats(raw: str, fast: bool) -> list[str]:
    chosen: list[str] = []
    for token in (t.strip().lower() for t in raw.split(",")):
        if not token:
            continue
        if token in GROUPS:
            items = list(GROUPS[token])
        elif token in EBOOK_FORMATS + AUDIO_FORMATS:
            items = [token]
        else:
            raise ValueError(f"formato desconhecido: {token}")
        for item in items:
            if item not in chosen:
                chosen.append(item)
    if fast:
        chosen = [f for f in chosen if f not in ("mobi", "azw3")]
    if not chosen:
        raise ValueError("nenhum formato selecionado")
    return chosen


def parse_bool(value: str) -> bool:
    lowered = value.strip().lower()
    if lowered in ("true", "1", "yes", "sim", "on"):
        return True
    if lowered in ("false", "0", "no", "nao", "não", "off"):
        return False
    raise argparse.ArgumentTypeError(f"valor booleano inválido: {value}")


def default_output(title: str) -> Path:
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    return Path.cwd() / "book_outputs" / slugify(title) / f"exports_{stamp}"


def parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Gera ebook e audiobook a partir de Markdown.")
    parser.add_argument("--source", required=True, help="arquivo .md ou pasta com .md")
    parser.add_argument("--formats", default="ebook",
                        help="epub,pdf,html,markdown,mobi,azw3,mp3,m4b ou grupos: ebook, audiobook, all")
    parser.add_argument("--strict-mode", type=parse_bool, default=True, metavar="{true,false}",
                        help="true (padrão): texto idêntico às fontes. false: remove sobras de IA")
    parser.add_argument("--title", default="")
    parser.add_argument("--subtitle", default="")
    parser.add_argument("--author", default="")
    parser.add_argument("--language", default="pt-BR", help="pt-BR (padrão) ou en-US")
    parser.add_argument("--publisher", default="")
    parser.add_argument("--year", default=str(dt.date.today().year))
    parser.add_argument("--isbn", default="")
    parser.add_argument("--cover", default="", help="imagem de capa (epub/mobi/azw3)")
    parser.add_argument("--voice", default="", help="voz edge-tts (padrão depende do idioma)")
    parser.add_argument("--rate", default="+0%", help="velocidade da narração, ex.: +10%%")
    parser.add_argument("--output", default="", help="pasta de saída (padrão: book_outputs/<slug>/exports_<data>)")
    parser.add_argument("--origin", default="markdown", choices=["markdown", "prompt"],
                        help="registro no manifest: texto veio de .md ou foi escrito a partir de um prompt")
    parser.add_argument("--fast", action="store_true", help="pula mobi/azw3 (como o compile_book.sh)")
    parser.add_argument("--dry-run", action="store_true", help="só monta o manuscrito e o manifest")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    # Windows consoles default to cp1252; progress output has emoji and accents.
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    args = parse_args(argv)
    try:
        formats = resolve_formats(args.formats, args.fast)
        sources = collect_sources(Path(args.source).expanduser().resolve())
    except ValueError as error:
        print(f"❌ {error}")
        return 2

    language = args.language if args.language in LANGUAGES else "pt-BR"
    labels = LANGUAGES[language]
    strict = args.strict_mode
    blocks, removed = load_blocks(sources, strict)

    title = args.title or first_heading(blocks[0].text) or Path(args.source).stem or labels["default_title"]
    meta = Meta(title=title, subtitle=args.subtitle, author=args.author, language=language,
                publisher=args.publisher, year=args.year, isbn=args.isbn)

    out_dir = Path(args.output).expanduser().resolve() if args.output else default_output(title)
    out_dir.mkdir(parents=True, exist_ok=True)

    cover = Path(args.cover).expanduser().resolve() if args.cover else None
    if cover and not cover.exists():
        print(f"❌ capa não encontrada: {cover}")
        return 2
    if cover:
        shutil.copy2(cover, out_dir / cover.name)
        cover = out_dir / cover.name

    voice = args.voice or labels["voice"]
    ctx = Context(blocks=blocks, meta=meta, strict=strict, out_dir=out_dir, cover=cover)
    ctx.manifest = {
        "title": title, "subtitle": args.subtitle, "author": args.author, "language": language,
        "strict_mode": strict, "origin": args.origin, "formats_requested": formats,
        "voice": voice, "rate": args.rate, "created_at": dt.datetime.now().isoformat(timespec="seconds"),
        "sources": [{"file": b.path.name, "sha256": b.sha256, "title": b.title} for b in blocks],
        "non_strict_removed_lines": removed, "formats": {},
    }

    manuscript = build_manuscript(blocks, meta)
    manuscript_path = out_dir / "manuscript.md"
    manuscript_path.write_text(manuscript, encoding="utf-8")

    missing = verify_verbatim(manuscript, blocks)
    ctx.manifest["verbatim_check"] = {"checked_blocks": len(blocks), "missing": missing, "ok": not missing}
    if missing:
        print(f"❌ verificação de texto falhou; nada foi exportado. Fontes não encontradas no manuscrito: {missing}")
        write_manifest(ctx)
        return 3

    print(f"📚 {title} | fontes: {len(blocks)} | modo estrito: {'sim' if strict else 'não'} | saída: {out_dir}")
    print("✅ texto das fontes confirmado no manuscrito (verbatim)")
    if removed:
        print(f"ℹ️  modo não estrito removeu {len(removed)} linha(s) de sobras de IA (veja o manifest)")

    if args.dry_run:
        for fmt in formats:
            ctx.manifest["formats"][fmt] = {"status": "dry-run"}
        write_manifest(ctx)
        print("🧪 dry-run: manuscrito e manifest gerados, nenhum formato foi exportado")
        return 0

    pandoc = find_tool("pandoc")
    failures = 0
    ebook_wanted = [f for f in formats if f in EBOOK_FORMATS]
    audio_wanted = [f for f in formats if f in AUDIO_FORMATS]
    ctx.manifest["tools"] = {
        "pandoc": tool_version([pandoc, "--version"]) if pandoc else None,
        "ffmpeg": tool_version(["ffmpeg", "-version"]) if find_tool("ffmpeg") else None,
        "edge_tts": "installed" if edge_tts_available() else None,
    }

    for fmt in ebook_wanted:
        print(f"📦 gerando {fmt}...")
        try:
            produced = build_ebook(fmt, ctx, pandoc)
            ctx.manifest["formats"][fmt] = {"status": "ok", "path": produced}
            print(f"   ✅ {produced}")
        except RuntimeError as error:
            failures += 1
            ctx.manifest["formats"][fmt] = {"status": "failed", "error": str(error)}
            print(f"   ❌ {fmt}: {error}")

    if audio_wanted:
        print("🎧 gerando audiobook (edge-tts)...")
        try:
            produced = build_audio(ctx, want_m4b="m4b" in audio_wanted)
            for fmt in audio_wanted:
                if fmt in produced:
                    ctx.manifest["formats"][fmt] = {"status": "ok", "path": produced[fmt]}
                    print(f"   ✅ {produced[fmt]}")
                else:
                    failures += 1
                    ctx.manifest["formats"][fmt] = {"status": "failed", "error": "não gerado"}
        except RuntimeError as error:
            for fmt in audio_wanted:
                failures += 1
                ctx.manifest["formats"][fmt] = {"status": "failed", "error": str(error)}
            print(f"   ❌ áudio: {error}")

    write_manifest(ctx)
    print(f"🏁 concluído: {len(formats) - failures} ok, {failures} com erro. Manifest: {out_dir / 'manifest.json'}")
    return 1 if failures else 0


def write_manifest(ctx: Context) -> None:
    (ctx.out_dir / "manifest.json").write_text(
        json.dumps(ctx.manifest, ensure_ascii=False, indent=2), encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
