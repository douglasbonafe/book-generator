#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""book_engine.py - turns Markdown sources into ebook and audiobook files.

Ebook formats (same toolchain as scripts/compile_book.sh in this repository):
    epub, pdf, html, markdown, mobi, azw3
Audiobook formats:
    mp3  (one file per chapter + the full book)
    m4b  (single audiobook file with chapter markers)

Source: one .md file, or a folder whose .md files are read in natural order
(non-recursive; files starting with "_" or "." are ignored).

STRICT MODE (default: true)
    The body text of every output is exactly the text of the source files.
    The engine only adds layout around it: YAML metadata, page breaks between
    source files and the table of contents generated by pandoc. After the
    manuscript is assembled, every source block is checked to appear verbatim
    in it; if one does not, nothing is exported.

NON-STRICT MODE (--strict-mode=false)
    The engine also removes AI-authoring leftovers (NOTE TO WRITER, Word count:,
    ...). Every removed line is written to the manifest. Editorial changes made
    by an agent before calling the engine must be recorded by that agent.

Audio text is derived from the same blocks by removing Markdown syntax only
(headings, emphasis, links, images, raw LaTeX/HTML). No word is rewritten.

Exit codes: 0 ok, 1 some requested format failed, 2 bad arguments or source,
3 verbatim check failed (nothing exported).
"""
